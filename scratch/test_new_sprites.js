console.log('Validating new sprites...');
let hasError = false;
for (const [key, rows] of Object.entries(NEW_SPRITES)) {
  const h = rows.length;
  const w = rows[0].length;
  for (let r = 0; r < h; r++) {
    const row = rows[r];
    if (row.length !== w) {
      console.error(`Error in ${key} row ${r}: expected length ${w}, got ${row.length}`);
      hasError = true;
    }
    for (let c = 0; c < w; c++) {
      const char = row[c];
      if (!(char in PALETTE)) {
        console.error(`Error in ${key} row ${r} col ${c}: unknown char '${char}'`);
        hasError = true;
      }
    }
  }
}

if (!hasError) {
  console.log('ALL ' + Object.keys(NEW_SPRITES).length + ' SPRITES ARE 100% VALID!');
} else {
  process.exit(1);
}
